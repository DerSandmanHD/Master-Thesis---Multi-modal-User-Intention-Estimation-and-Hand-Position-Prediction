"""Build supplementary thesis tables from saved results, without rerunning experiments.

Supply the processed-artifact root and a NEW output directory. Original reports
and thesis sources are read-only. Input hashes are verified against the release
lock before generating six tables, one figure and a provenance manifest.
"""
from pathlib import Path
import argparse
import sys
import csv
import hashlib
import json
import statistics

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "Training/reports/dataset_v3_causal_20260815_n214_5d136a34"
THESIS = None
DEST = None
LOCK_FILES = {}
INPUTS = {}
OUTPUTS = {}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read(path):
    relative = path.relative_to(ROOT).as_posix()
    payload = path.read_bytes()
    digest = hashlib.sha256(payload).hexdigest()
    expected = LOCK_FILES[relative]
    if len(payload) != expected["size_bytes"] or digest != expected["sha256"]:
        raise ValueError(f"Input differs from release inventory: {relative}")
    INPUTS[relative] = digest
    return payload.decode("utf-8")


def rows(path):
    return list(csv.DictReader(read(path).splitlines()))


def write(name, value):
    path = DEST / name
    path.write_text("% Generated by Training/build_supplementary_thesis.py; do not edit numbers.\n" + value + "\n")
    OUTPUTS[str(path.relative_to(THESIS))] = sha(path)


def pm(mean, sd, digits=2):
    return rf"${float(mean):.{digits}f} \pm {float(sd):.{digits}f}$"


def seed(mean, sd, digits):
    return rf"\shortstack{{${float(mean):.{digits}f}$\\[0pt]$\pm {float(sd):.{digits}f}$}}"


def table(caption, label, columns, header, body, short, colsep=4):
    return "\n".join([
        r"\begin{table}[!htbp]", r"\centering", r"\small",
        rf"\caption[{short}]{{{caption}}}", rf"\label{{{label}}}",
        rf"\setlength{{\tabcolsep}}{{{colsep}pt}}", rf"\begin{{tabular}}{{{columns}}}",
        r"\toprule", header + r" \\", r"\midrule", *body,
        r"\bottomrule", r"\end{tabular}", r"\end{table}",
    ])


def main(argv=None):
    global ROOT, REPORTS, THESIS, DEST, LOCK_FILES
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="Repository-layout processed-artifact package")
    parser.add_argument("--output-dir", type=Path, required=True,
                        help="New directory; existing directories are refused")
    args = parser.parse_args(argv)
    ROOT = args.root.resolve()
    REPORTS = ROOT / "Training/reports/dataset_v3_causal_20260815_n214_5d136a34"
    THESIS = args.output_dir.resolve()
    DEST = THESIS / "supplementary_tables"
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "reproducibility"))
    from artifacts import load_lock, verify
    lock = load_lock(Path(__file__).resolve().parents[1] /
                     "reproducibility/processed_artifacts.lock.json")
    required = [
        "Data_collection/object_marker_free_v1/mixed_runs_v1/comparison.json",
        *[str((REPORTS / name).relative_to(ROOT)) for name in [
            "terminal_input_timing_v1/summary.csv",
            "terminal_residual_diagnosis_v1/summary.csv",
            "terminal_residual_diagnosis_v1/validation_comparison.csv",
            "terminal_residual_shrinkage_v1/validation_grid.csv",
            "terminal_residual_shrinkage_v1/test_summary.csv",
            "terminal_residual_shrinkage_v1/selection.json"]]]
    LOCK_FILES = {x["path"]: x for x in lock["files"] if x["path"] in required}
    if set(LOCK_FILES) != set(required):
        raise ValueError("Required input missing from release inventory")
    failures = [(i, status) for i, (_, status) in enumerate(verify(ROOT, list(LOCK_FILES.values())))
                if status != "verified"]
    if failures:
        raise ValueError(f"Input verification failed (indices/status): {failures}")
    THESIS.mkdir(parents=True, exist_ok=False)
    DEST.mkdir()
    (THESIS / "figures").mkdir()
    INPUTS.clear()
    OUTPUTS.clear()
    adapt = json.loads(read(ROOT / "Data_collection/object_marker_free_v1/mixed_runs_v1/comparison.json"))
    body = []
    domains = [("original", "Old recordings: original inputs"),
               ("objects_masked", "Old recordings: object features masked"),
               ("new_marker_free", "New recordings: no object markers")]
    variants = [("unchanged", "Unchanged source"), ("finetune", "New-only fine-tuning"),
                ("scratch", "New-only from scratch"), ("mixed_finetune", "Mixed fine-tuning")]
    for i, (domain, title) in enumerate(domains):
        if i:
            body.append(r"\midrule")
        body.append(rf"\multicolumn{{4}}{{l}}{{\textit{{{title}}}}} \\")
        for variant, title in variants:
            metrics = adapt[domain][variant]
            cells = [seed(metrics[m]["mean"], metrics[m]["std"], d) for m, d in
                     [("intention_macro_f1", 4), ("hand_macro_f1", 4), ("position_mean_cm", 2)]]
            body.append(" & ".join([title, *cells]) + r" \\[2pt]")
    write("adaptation.tex", table(
        r"Follow-up $t+1$\,s adaptation and retention. Values are mean $\pm$ sample SD over seeds 42--44. Classification uses 2,199 old or 915 new test windows. Position uses the same 181/217 old or 282/282 new valid targets for every variant, with both wrist references available, predicted receiving hands, and no intention gate. Object masking changes input features only. The source family differs from the principal matrix in Table~\ref{tab:model_comparison}.",
        "tab:supp_adaptation", "lccc", r"\textbf{Training variant} & \textbf{Intention F1} & \textbf{Hand F1} & \textbf{Position [cm]}", body,
        "Follow-up adaptation and old-domain retention"))

    timing = rows(REPORTS / "terminal_input_timing_v1/summary.csv")
    for scheme, axis, output, label, short in [
        ("disjoint60", "block", "timing_disjoint.tex", "tab:supp_disjoint", "Disjoint terminal input blocks"),
        ("frozen_stride10", "remaining", "timing_remaining.tex", "tab:supp_remaining", "Terminal error by remaining time"),
    ]:
        selected = [x for x in timing if x["scheme"] == scheme and x["axis"] == axis
                    and x["regime"] == "strictly_before_aggregation" and x["method"] == "learned_end_to_end"]
        # The report names the disjoint axis 'block_index'. Resolve explicitly.
        if not selected and scheme == "disjoint60":
            selected = [x for x in timing if x["scheme"] == scheme and x["axis"].startswith("block")
                        and x["regime"] == "strictly_before_aggregation" and x["method"] == "learned_end_to_end"]
        assert selected, (scheme, sorted({x["axis"] for x in timing if x["scheme"] == scheme}))
        selected.sort(key=lambda x: int(x["order"]))
        body = []
        for row in selected:
            baseline = next(x for x in timing if all(x[k] == row[k] for k in ["scheme", "axis", "regime", "bin"])
                            and x["method"] == "persistence_predicted_hand")
            title = row["bin"].replace("–", "--").replace("≥", r"$\geq$ ")
            assert row["windows"] == baseline["windows"]
            n = int(row["windows"])
            body.append(" & ".join([title, row["windows"], row["sequences"],
                pm(row["mean_cm"], row["seed_sd_cm"]) if n else "--",
                pm(baseline["mean_cm"], baseline["seed_sd_cm"]) if n else "--"]) + r" \\")
        first = "Input rows" if scheme == "disjoint60" else "Remaining time"
        caption = (r"Non-overlapping 60-sample blocks counted from the first annotated handover row. Only pure-future terminal targets and valid references for both hands are retained. The endpoint precedes every capture contributing to the target aggregate. Incomplete blocks are omitted. Counts are distinct windows and recordings, not multiplied by seeds. Errors in cm use predicted hands and matched persistence; mean $\pm$ sample SD over three seeds."
                   if scheme == "disjoint60" else
                   r"Original 60-sample windows with stride 10, grouped by time from window endpoint to the last capture contributing to the terminal target. All 201 windows from 20 recordings are pure-future: their endpoints also precede the first contributing capture. Time bins are left-inclusive and right-exclusive. Counts vary between bins; recordings may contribute to several bins. Errors in cm use predicted hands and matched persistence; mean $\pm$ sample SD over three seeds.")
        write(output, table(caption, label, "lrrcc", rf"\textbf{{{first}}} & \textbf{{Windows}} & \textbf{{Videos}} & \textbf{{Model [cm]}} & \textbf{{Persistence [cm]}}", body, short))

    diagnostic = rows(REPORTS / "terminal_residual_diagnosis_v1/summary.csv")
    validation = rows(REPORTS / "terminal_residual_diagnosis_v1/validation_comparison.csv")
    raw_grid = rows(REPORTS / "terminal_residual_shrinkage_v1/validation_grid.csv")
    grid = []
    for family, alpha in sorted({(x["checkpoint"], float(x["alpha"])) for x in raw_grid}):
        group = [x for x in raw_grid if x["checkpoint"] == family and float(x["alpha"]) == alpha]
        assert {int(x["seed"]) for x in group} == {42, 43, 44}
        values = [float(x["predicted_hand_cm"]) for x in group]
        grid.append({"checkpoint": family, "alpha": alpha,
                     "predicted_hand_cm": statistics.mean(values),
                     "predicted_hand_sd": statistics.stdev(values)})
    test = rows(REPORTS / "terminal_residual_shrinkage_v1/test_summary.csv")
    selection = json.loads(read(REPORTS / "terminal_residual_shrinkage_v1/selection.json"))
    body = []
    for family, title in [("best_intention", "Intention-selected"), ("best_pose", "Pose-selected (diagnostic)")]:
        r = next(x for x in diagnostic if x["checkpoint"] == family and x["axis"] == "overall")
        vals = [float(x["model_predicted_hand_cm"]) for x in validation if x["checkpoint"] == family]
        # Aggregate the validation grid over seeds; test_summary already contains seed summaries.
        baseline_val = next(x for x in grid if x["checkpoint"] == family and float(x["alpha"]) == 0)
        baseline_test = next(x for x in test if x["checkpoint"] == family and x["variant"] == "persistence")
        body.append(rf"\multicolumn{{4}}{{l}}{{\textit{{{title}}}}} \\")
        body.append(" & ".join(["Model", pm(statistics.mean(vals), statistics.stdev(vals)),
                                pm(r["model_predicted_hand_cm_mean"], r["model_predicted_hand_cm_seed_sd"]),
                                pm(r["model_gt_cm_mean"], r["model_gt_cm_seed_sd"])]) + r" \\")
        body.append(" & ".join(["Matched persistence", pm(baseline_val["predicted_hand_cm"], baseline_val["predicted_hand_sd"]),
                                pm(baseline_test["predicted_hand_cm"], baseline_test["predicted_hand_sd"]),
                                f'${float(baseline_test["gt_hand_cm"]):.2f}$']) + r" \\")
        if family == "best_intention":
            body.append(r"\midrule")
    write("checkpoints.tex", table(
        r"Terminal checkpoint diagnosis. Validation: 256 identical pure-future windows; test: 201 identical windows from 20 recordings. Mean Euclidean errors in cm are mean $\pm$ sample SD over seeds 42--44. The predicted-hand persistence row uses the same hand decision as its checkpoint family. The known-hand (GT) baseline is shared and deterministic. Pose-selected checkpoints were previously selected using the broader original validation pose objective; this table applies the stricter common forecasting cohort. No test-based checkpoint reselection is performed.",
        "tab:supp_checkpoints", "lccc", r"\textbf{Method} & \shortstack{\textbf{Validation}\\\textbf{predicted hand}} & \shortstack{\textbf{Test}\\\textbf{predicted hand}} & \shortstack{\textbf{Test}\\\textbf{GT hand}}", body,
        "Validation and test comparison of terminal checkpoint families"))

    displacement = sorted([x for x in diagnostic if x["checkpoint"] == "best_intention" and x["axis"] == "displacement"], key=lambda x: int(x["order"]))
    assert sum(int(x["windows"]) for x in displacement) == 201
    body = []
    for r in displacement:
        label = r["bin"].replace("–", "--").replace("≥", r"$\geq$ ")
        body.append(" & ".join([label, r["windows"], r["sequences"],
            f'${float(r["actual_displacement_cm_mean"]):.2f}$', f'${float(r["predicted_displacement_cm_mean"]):.2f}$',
            pm(r["model_gt_cm_mean"], r["model_gt_cm_seed_sd"])]) + r" \\")
    write("displacements.tex", table(
        r"Residual diagnosis of the intention-selected terminal model, using the known receiving hand on the 201 pure-future test windows. Bins are based on the true distance from the observed reference to the fixed terminal target, not on information available at inference. All distances are in cm. Mean true distance also equals the persistence error. Model error includes seed SD; other columns show seed means. Counts are not multiplied by three, and recordings may occur in multiple bins.",
        "tab:supp_displacement", "lrrccc", r"\shortstack{\textbf{True distance}\\\textbf{bin [cm]}} & \textbf{Windows} & \textbf{Videos} & \shortstack{\textbf{True distance}\\\textbf{/ persistence}} & \shortstack{\textbf{Predicted}\\\textbf{displacement}} & \shortstack{\textbf{Model}\\\textbf{error}}", body,
        "Terminal residuals grouped by true remaining displacement", colsep=2))

    body = []
    for family, title in [("best_intention", "Intention-selected (primary)"), ("best_pose", "Pose-selected (diagnostic)")]:
        body.append(rf"\multicolumn{{5}}{{l}}{{\textit{{{title}}}}} \\")
        for variant, label in [("persistence", "Persistence"), ("selected", "Validation-selected"), ("original", "Original model")]:
            r = next(x for x in test if x["checkpoint"] == family and x["variant"] == variant)
            v = next(x for x in grid if x["checkpoint"] == family and abs(float(x["alpha"])-float(r["alpha"])) < 1e-9)
            if variant == "selected":
                assert float(r["alpha"]) == selection["selected"][family]["alpha"]
            body.append(" & ".join([label, f'${float(r["alpha"]):g}$', f'${float(v["predicted_hand_cm"]):.2f}$',
                                    pm(r["predicted_hand_cm"], r["predicted_hand_sd"]),
                                    pm(r["gt_hand_cm"], r["gt_hand_sd"])]) + r" \\")
        if family == "best_intention":
            body.append(r"\midrule")
    write("attenuation.tex", table(
        r"Residual attenuation without retraining. One factor per checkpoint family is selected on the 256 common pure-future validation windows, then frozen before test prediction exports are read. Only persistence, the selected factor, and the original model are evaluated on the 201-window test cohort. Validation shows mean predicted-hand error; test shows mean $\pm$ sample SD across three seeds, in cm. GT-hand test values are diagnostic and do not select the factor.",
        "tab:supp_attenuation", "lcccc", r"\textbf{Variant} & $\boldsymbol{\alpha}$ & \shortstack{\textbf{Validation}\\\textbf{predicted hand}} & \shortstack{\textbf{Test}\\\textbf{predicted hand}} & \shortstack{\textbf{Test}\\\textbf{GT hand}}", body,
        "Validation-selected residual attenuation and fixed test results"))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 10, "pdf.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False})
    fig, ax = plt.subplots(figsize=(5.5, 2.8), layout="constrained")
    xx = list(range(len(displacement)))
    ax.plot(xx, [float(x["actual_displacement_cm_mean"]) for x in displacement], "o-", color="#245a81", label="True remaining displacement")
    ax.errorbar(xx, [float(x["predicted_displacement_cm_mean"]) for x in displacement],
                yerr=[float(x["predicted_displacement_cm_seed_sd"]) for x in displacement],
                fmt="s-", capsize=3, color="#b65027", label="Predicted residual length")
    ax.set_xticks(xx, [x["bin"].replace("–", "-") + "\nN=" + x["windows"] for x in displacement])
    ax.set_xlabel("True remaining-displacement bin [cm]")
    ax.set_ylabel("Mean distance [cm]")
    ax.set_ylim(bottom=0)
    ax.grid(axis="y", alpha=.2)
    ax.legend(frameon=False, loc="upper left", fontsize=9)
    fp = THESIS / "figures/fig_supp_residual_lengths.pdf"
    fig.savefig(fp)
    plt.close(fig)
    OUTPUTS[str(fp.relative_to(THESIS))] = sha(fp)

    manifest = {"purpose": "Supplementary thesis integration; original experiment reports are read-only",
                "generator_sha256": sha(Path(__file__)),
                "seeds": [42, 43, 44], "inputs_sha256": INPUTS, "outputs_sha256": OUTPUTS,
                "checks": {"terminal_test_windows": 201, "terminal_validation_windows": 256,
                           "displacement_partition_complete": True, "selected_alpha_matches_frozen_selection": True}}
    (DEST / "artifact_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Generated {len(OUTPUTS)} artifacts from {len(INPUTS)} result files.")


if __name__ == "__main__":
    main()
